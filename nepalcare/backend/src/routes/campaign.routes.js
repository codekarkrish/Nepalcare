import { Router } from 'express';
import { listPublic,detail,create,getCampaignImage,getNGOCampaignImage,myCampaigns,ngoManagement,ngoDonations,ngoFinancialSummary,requestDeletion,listDeletionRequests,reviewDeletionRequest,update,submit,pending,review,citizenSummary,adminOverview } from '../controllers/campaign.controller.js';
import { authenticate,requireRole,requirePermission } from '../middleware/auth.js';
import { validateBody } from '../middleware/validate.js';
import campaignImageUpload from '../middleware/campaignImageUpload.js';
const router=Router();
const authorizeReviewStatus=(req,res,next)=>{
 const permission=req.body.status==='APPROVED'?'campaign.approve':req.body.status==='REJECTED'?'campaign.reject':'campaign.review';
 return requirePermission(permission)(req,res,next);
};
router.get('/',listPublic);
router.get('/admin/pending',authenticate,requireRole('ADMIN'),requirePermission('campaign.review'),pending);
router.patch('/admin/:id/approve',authenticate,requireRole('ADMIN'),requirePermission('campaign.approve'),(_req,_res,next)=>{_req.body.status='APPROVED';next();},review);
router.patch('/admin/:id/reject',authenticate,requireRole('ADMIN'),requirePermission('campaign.reject'),validateBody(['reviewNote']),(_req,_res,next)=>{_req.body.status='REJECTED';next();},review);
router.patch('/admin/:id/resubmission',authenticate,requireRole('ADMIN'),requirePermission('campaign.review'),validateBody(['reviewNote']),(_req,_res,next)=>{_req.body.status='RESUBMISSION_REQUIRED';next();},review);
router.patch('/admin/:id/review',authenticate,requireRole('ADMIN'),validateBody(['status']),authorizeReviewStatus,review);
router.get('/admin/overview',authenticate,requireRole('ADMIN'),adminOverview);
router.get('/admin/deletion-requests',authenticate,requireRole('ADMIN'),requirePermission('campaign.deletion.review'),listDeletionRequests);
router.patch('/admin/deletion-requests/:campaignId/:requestId',authenticate,requireRole('ADMIN'),requirePermission('campaign.deletion.review'),validateBody(['status']),reviewDeletionRequest);
router.get('/citizens/me/summary',authenticate,requireRole('CITIZEN'),citizenSummary);
router.get('/ngo/mine',authenticate,requireRole('NGO'),myCampaigns);
router.get('/ngo/donations',authenticate,requireRole('NGO'),ngoDonations);
router.get('/ngo/financial-summary',authenticate,requireRole('NGO'),ngoFinancialSummary);
router.get('/ngo/:id/management',authenticate,requireRole('NGO'),ngoManagement);
router.get('/ngo/:id/images/:kind',authenticate,requireRole('NGO'),getNGOCampaignImage);
router.post('/:id/deletion-requests',authenticate,requireRole('NGO'),validateBody(['reason']),requestDeletion);
router.get('/:id/images/:kind',getCampaignImage);
router.post('/',authenticate,requireRole('NGO'),campaignImageUpload.fields([{name:'coverImage',maxCount:1},{name:'qrImage',maxCount:1}]),validateBody(['title','description','category','location']),create);
router.patch('/:id',authenticate,requireRole('NGO'),campaignImageUpload.fields([{name:'coverImage',maxCount:1},{name:'qrImage',maxCount:1}]),update);
router.post('/:id/submit',authenticate,requireRole('NGO'),submit);
router.get('/:id',detail);
export default router;
