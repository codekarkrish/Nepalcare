import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { connectDB } from './config/db.js';
import authRoutes from './routes/auth.routes.js';
import ngoRoutes from './routes/ngo.routes.js';
import campaignRoutes from './routes/campaign.routes.js';
import volunteerRoutes from './routes/volunteer.routes.js';
import donationRoutes from './routes/donation.routes.js';
import reliefRoutes from './routes/relief.routes.js';
import adminRoutes from './routes/admin.routes.js';
import itemDonationRoutes from './routes/itemDonation.routes.js';
import { notFound,errorHandler } from './middleware/errorHandler.js';
const app=express();
app.disable('x-powered-by');
app.use(helmet());
const allowedOrigins=(process.env.CLIENT_URL||'http://localhost:5173').split(',').map(s=>s.trim());
app.use(cors({origin(origin,callback){if(!origin||allowedOrigins.includes(origin))return callback(null,true);return callback(new Error('Origin is not allowed by CORS.'));},credentials:true}));
app.use(express.json({limit:'1mb'}));
app.use(morgan(process.env.NODE_ENV==='production'?'combined':'dev'));
app.get('/api/health',(_req,res)=>res.json({success:true,message:'NepalCare API is running'}));
const authLimiter=rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false,message:{success:false,message:'Too many authentication requests. Try again later.'}});
app.use('/api/auth/login',authLimiter);app.use('/api/auth/register',authLimiter);
app.use('/api/auth',authRoutes);
app.use('/api/ngos',ngoRoutes);
app.use('/api/campaigns',campaignRoutes);
app.use('/api/volunteers',volunteerRoutes);
app.use('/api/donations',donationRoutes);
app.use('/api/relief',reliefRoutes);
app.use('/api/item-donations',itemDonationRoutes);
app.use('/api/admin',adminRoutes);
app.use(notFound);app.use(errorHandler);
const port=Number(process.env.PORT)||5000;
async function start(){
 if(!process.env.JWT_SECRET||process.env.JWT_SECRET.length<32)throw new Error('Missing or weak JWT_SECRET. Set a random secret of at least 32 characters in backend/.env.');
 await connectDB();
 app.listen(port,()=>console.log(`NepalCare API listening on http://localhost:${port}`));
}
start().catch(error=>{console.error(`Startup failed: ${error.message}`);process.exit(1);});
